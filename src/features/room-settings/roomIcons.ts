/** Groups filtered by a search query (matches the emoji or its words). */
export function filterRoomIcons(query: string): RoomIconGroup[] {
  const q = query.trim().toLowerCase();
  if (!q) return [...ROOM_ICON_GROUPS];
  return ROOM_ICON_GROUPS.map((group) => ({
    ...group,
    icons: group.icons.filter(
      ([icon, words]) => icon === q || words.includes(q) || group.label.toLowerCase().includes(q),
    ),
  })).filter((group) => group.icons.length > 0);
}
